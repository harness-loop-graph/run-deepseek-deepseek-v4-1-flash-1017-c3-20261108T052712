import { createReadStream } from 'node:fs';
import { mkdir, stat, unlink, writeFile } from 'node:fs/promises';
import { basename, extname, join, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { Inject, Injectable } from '@nestjs/common';
import { Pool } from 'pg';
import { DATABASE_POOL } from '../database/database.tokens';
import { attachmentsDir, maxUploadBytes } from '../common/app-config';
import {
  forbidden,
  notFound,
  payloadTooLarge,
  unsupportedMediaType,
  validationError,
} from '../common/errors';
import { AuthUser, canReadClinicalHistory } from '../auth/auth-user';
import { AuditService, AUDIT_ACTIONS } from '../audit/audit.service';
import {
  AppointmentRecord,
  toAppointmentRecord,
  APPOINTMENT_SELECT,
  AppointmentRow,
} from '../appointments/appointment.repository';
import { AttachmentSummary, EncounterRecord, toEncounterRecord } from '../appointments/appointments.service';

/**
 * Clinical content: EP-12 (chronology), EP-13 (attachment upload) and EP-14
 * (attachment download).
 *
 * RF-10 is enforced in the queries: a patient reads only their own history, a
 * professional only the history of a patient with an assigned appointment, and
 * staff/admin never reach this service (the routes declare it).
 *
 * RF-17: allowed types are PDF/JPEG/PNG, at most 5 MB, the stored name is
 * generated by the server, and the bytes live outside any served directory —
 * they are only reachable through EP-14 with a permission check.
 */

interface EncounterRow {
  id: number;
  cita_id: number;
  version: number;
  notas: string;
  diagnostico: string;
  autor_profesional_id: number;
  reemplaza_a_id: number | null;
  creado_en: Date;
  paciente_id: number;
  profesional_id: number;
}

interface AttachmentRow {
  id: number;
  encuentro_id: number;
  nombre_original: string;
  nombre_almacenado: string;
  mime_type: string;
  tamano_bytes: number;
  creado_en: Date;
}

export interface HistoryEntry extends EncounterRecord {
  appointment: {
    id: number;
    start: string;
    status: AppointmentRecord['status'];
    professional: AppointmentRecord['professional'];
  };
}

export interface ClinicalHistory {
  patientId: number;
  encounters: HistoryEntry[];
}

export interface StoredAttachment {
  id: number;
  encounterId: number;
  filename: string;
  mimeType: string;
  sizeBytes: number;
  createdAt: string;
}

export interface AttachmentDownload {
  filename: string;
  mimeType: string;
  sizeBytes: number;
  body: Buffer;
}

/** Signature check: the declared type must match the actual bytes. */
const SIGNATURES: Record<string, (buffer: Buffer) => boolean> = {
  'application/pdf': (buffer) => buffer.subarray(0, 5).toString('latin1') === '%PDF-',
  'image/jpeg': (buffer) => buffer.length > 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff,
  'image/png': (buffer) =>
    buffer.length > 8 &&
    buffer[0] === 0x89 &&
    buffer[1] === 0x50 &&
    buffer[2] === 0x4e &&
    buffer[3] === 0x47,
};

const EXTENSIONS: Record<string, string> = {
  'application/pdf': '.pdf',
  'image/jpeg': '.jpg',
  'image/png': '.png',
};

/** RF-17: server-side filename sanitization (no separators, no traversal). */
export function sanitizeFilename(original: string, mimeType: string): string {
  const base = basename(original.replace(/\\/g, '/'));
  const withoutExtension = base.slice(0, base.length - extname(base).length);
  const cleaned = withoutExtension
    .normalize('NFKD')
    .replace(/[^A-Za-z0-9._-]+/g, '_')
    .replace(/^[._]+/, '')
    .slice(0, 80);
  const safe = cleaned === '' ? 'adjunto' : cleaned;
  return `${safe}${EXTENSIONS[mimeType] ?? ''}`;
}

@Injectable()
export class EncountersService {
  constructor(
    @Inject(DATABASE_POOL) private readonly pool: Pool,
    private readonly audit: AuditService,
  ) {}

  /** EP-12: chronology of a patient, newest first, with attachments. */
  async clinicalHistory(user: AuthUser, patientId: number): Promise<ClinicalHistory> {
    const patientExists = await this.pool.query<{ exists: boolean }>(
      'SELECT EXISTS (SELECT 1 FROM paciente WHERE id = $1) AS exists',
      [patientId],
    );
    if (patientExists.rows[0]?.exists !== true) {
      throw notFound('Patient not found.');
    }

    const assigned = await this.professionalHasAppointment(user, patientId);
    if (!canReadClinicalHistory(user, patientId, assigned)) {
      throw forbidden('You are not allowed to read this clinical history.');
    }

    const rows = await this.pool.query<EncounterRow>(
      `SELECT e.id, e.cita_id, e.version, e.notas, e.diagnostico, e.autor_profesional_id,
              e.reemplaza_a_id, e.creado_en, c.paciente_id, c.profesional_id
         FROM encuentro e
         JOIN cita c ON c.id = e.cita_id
        WHERE c.paciente_id = $1
        ORDER BY e.creado_en DESC, e.id DESC`,
      [patientId],
    );

    const appointments = await this.pool.query<AppointmentRow>(
      `${APPOINTMENT_SELECT} WHERE c.paciente_id = $1`,
      [patientId],
    );
    const byId = new Map(appointments.rows.map((row) => [row.id, toAppointmentRecord(row)]));

    const attachments = await this.attachmentsFor(rows.rows.map((row) => row.id));

    const encounters: HistoryEntry[] = rows.rows.map((row) => {
      const appointment = byId.get(row.cita_id);
      return {
        ...toEncounterRecord(row, attachments.get(row.id) ?? []),
        appointment: {
          id: row.cita_id,
          start: appointment?.start ?? row.creado_en.toISOString(),
          status: appointment?.status ?? 'scheduled',
          professional: appointment?.professional ?? {
            id: row.profesional_id,
            nombre: '',
            apellidos: '',
            especialidad: '',
          },
        },
      };
    });

    await this.audit.recordFor(user, {
      action: AUDIT_ACTIONS.clinicalHistoryRead,
      resourceType: 'paciente',
      resourceId: patientId,
      metadata: { encounters: encounters.length },
    });

    return { patientId, encounters };
  }

  /** EP-13: the author professional attaches a file to their own encounter. */
  async upload(
    user: AuthUser,
    encounterId: number,
    file: { originalname: string; mimetype: string; size: number; buffer: Buffer } | undefined,
  ): Promise<StoredAttachment> {
    const encounter = await this.requireEncounter(encounterId);
    const professionalId = user.professionalId;

    if (professionalId === undefined || encounter.autor_profesional_id !== professionalId) {
      throw forbidden('Only the author professional can attach files to this encounter.');
    }

    if (file === undefined) {
      throw validationError('body.file: a file is required');
    }
    if (file.size <= 0) {
      throw validationError('body.file: the file is empty');
    }
    if (file.size > maxUploadBytes()) {
      throw payloadTooLarge();
    }
    if (!(file.mimetype in SIGNATURES)) {
      throw unsupportedMediaType('Only PDF, JPEG and PNG files are accepted.');
    }
    if (!SIGNATURES[file.mimetype](file.buffer)) {
      throw unsupportedMediaType('The file content does not match its declared type.');
    }

    const directory = resolve(attachmentsDir());
    await mkdir(directory, { recursive: true });

    const storedName = `${randomUUID()}${EXTENSIONS[file.mimetype]}`;
    const target = join(directory, storedName);
    await writeFile(target, file.buffer, { mode: 0o640 });

    const displayName = sanitizeFilename(file.originalname, file.mimetype);

    try {
      const inserted = await this.pool.query<AttachmentRow>(
        `INSERT INTO adjunto
           (encuentro_id, nombre_original, nombre_almacenado, mime_type, tamano_bytes, subido_por)
         VALUES ($1, $2, $3, $4, $5, $6)
         RETURNING id, encuentro_id, nombre_original, nombre_almacenado, mime_type,
                   tamano_bytes, creado_en`,
        [encounterId, displayName, storedName, file.mimetype, file.size, professionalId],
      );
      const row = inserted.rows[0];

      await this.audit.recordFor(user, {
        action: AUDIT_ACTIONS.attachmentCreated,
        resourceType: 'adjunto',
        resourceId: row.id,
        metadata: { encounterId, mimeType: file.mimetype, sizeBytes: file.size },
      });

      return {
        id: row.id,
        encounterId: row.encuentro_id,
        filename: row.nombre_original,
        mimeType: row.mime_type,
        sizeBytes: row.tamano_bytes,
        createdAt: row.creado_en.toISOString(),
      };
    } catch (error) {
      await unlink(target).catch(() => undefined);
      throw error;
    }
  }

  /** EP-14: streams an attachment to its author or to the owning patient. */
  async download(user: AuthUser, attachmentId: number): Promise<AttachmentDownload> {
    const found = await this.pool.query<AttachmentRow & { paciente_id: number; autor: number }>(
      `SELECT a.id, a.encuentro_id, a.nombre_original, a.nombre_almacenado, a.mime_type,
              a.tamano_bytes, a.creado_en, c.paciente_id, e.autor_profesional_id AS autor
         FROM adjunto a
         JOIN encuentro e ON e.id = a.encuentro_id
         JOIN cita c ON c.id = e.cita_id
        WHERE a.id = $1`,
      [attachmentId],
    );
    const row = found.rows[0];
    if (row === undefined) {
      throw notFound('Attachment not found.');
    }

    const isPatient = user.patientId !== undefined && user.patientId === row.paciente_id;
    const isAuthor = user.professionalId !== undefined && user.professionalId === row.autor;
    if (!isPatient && !isAuthor) {
      throw forbidden('You are not allowed to download this attachment.');
    }

    const target = join(resolve(attachmentsDir()), basename(row.nombre_almacenado));
    let body: Buffer;
    try {
      const info = await stat(target);
      if (!info.isFile()) {
        throw notFound('Attachment not found.');
      }
      body = await readFileBuffer(target);
    } catch {
      throw notFound('Attachment not found.');
    }

    await this.audit.recordFor(user, {
      action: AUDIT_ACTIONS.attachmentRead,
      resourceType: 'adjunto',
      resourceId: row.id,
      metadata: { encounterId: row.encuentro_id },
    });

    return {
      filename: row.nombre_original,
      mimeType: row.mime_type,
      sizeBytes: row.tamano_bytes,
      body,
    };
  }

  private async requireEncounter(encounterId: number): Promise<EncounterRow> {
    const result = await this.pool.query<EncounterRow>(
      `SELECT e.id, e.cita_id, e.version, e.notas, e.diagnostico, e.autor_profesional_id,
              e.reemplaza_a_id, e.creado_en, c.paciente_id, c.profesional_id
         FROM encuentro e
         JOIN cita c ON c.id = e.cita_id
        WHERE e.id = $1`,
      [encounterId],
    );
    const row = result.rows[0];
    if (row === undefined) {
      throw notFound('Encounter not found.');
    }
    return row;
  }

  /** RF-10: a professional needs an appointment (past or future) with the patient. */
  private async professionalHasAppointment(user: AuthUser, patientId: number): Promise<boolean> {
    if (user.professionalId === undefined) {
      return false;
    }
    const result = await this.pool.query<{ exists: boolean }>(
      `SELECT EXISTS (
         SELECT 1 FROM cita WHERE profesional_id = $1 AND paciente_id = $2
       ) AS exists`,
      [user.professionalId, patientId],
    );
    return result.rows[0]?.exists === true;
  }

  private async attachmentsFor(encounterIds: number[]): Promise<Map<number, AttachmentSummary[]>> {
    const grouped = new Map<number, AttachmentSummary[]>();
    if (encounterIds.length === 0) {
      return grouped;
    }
    const result = await this.pool.query<AttachmentRow>(
      `SELECT id, encuentro_id, nombre_original, nombre_almacenado, mime_type, tamano_bytes, creado_en
         FROM adjunto
        WHERE encuentro_id = ANY($1::int[])
        ORDER BY creado_en ASC, id ASC`,
      [encounterIds],
    );
    for (const row of result.rows) {
      const bucket = grouped.get(row.encuentro_id) ?? [];
      bucket.push({
        id: row.id,
        filename: row.nombre_original,
        mimeType: row.mime_type,
        sizeBytes: row.tamano_bytes,
        createdAt: row.creado_en.toISOString(),
      });
      grouped.set(row.encuentro_id, bucket);
    }
    return grouped;
  }
}

/** Reads a stored attachment; kept separate so the streaming path is explicit. */
export function readFileBuffer(path: string): Promise<Buffer> {
  return new Promise((resolvePromise, reject) => {
    const chunks: Buffer[] = [];
    const stream = createReadStream(path);
    stream.on('data', (chunk: Buffer | string) => {
      chunks.push(typeof chunk === 'string' ? Buffer.from(chunk) : chunk);
    });
    stream.on('end', () => resolvePromise(Buffer.concat(chunks)));
    stream.on('error', reject);
  });
}
